create table if not exists public.game_analyses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  platform text not null check (platform in ('lichess', 'chesscom')),
  external_username text not null,
  game_id text not null,
  accuracy numeric(5,2) not null check (accuracy >= 0 and accuracy <= 100),
  themes jsonb not null default '{}'::jsonb,
  analyzed_at bigint not null,
  created_at timestamptz not null default now(),
  unique (user_id, platform, game_id)
);

create index if not exists game_analyses_user_date_idx
  on public.game_analyses (user_id, analyzed_at desc);

alter table public.game_analyses enable row level security;

drop policy if exists "Players can read their own analyses" on public.game_analyses;
create policy "Players can read their own analyses"
  on public.game_analyses for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Players can insert their own analyses" on public.game_analyses;
create policy "Players can insert their own analyses"
  on public.game_analyses for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Players can update their own analyses" on public.game_analyses;
create policy "Players can update their own analyses"
  on public.game_analyses for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Players can delete their own analyses" on public.game_analyses;
create policy "Players can delete their own analyses"
  on public.game_analyses for delete
  to authenticated
  using (auth.uid() = user_id);

grant select, insert, update, delete on public.game_analyses to authenticated;
grant usage, select on sequence public.game_analyses_id_seq to authenticated;
